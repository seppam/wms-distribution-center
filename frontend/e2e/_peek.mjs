import { chromium } from '@playwright/test';
const S = process.argv[2];
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:5173/login');
await page.getByLabel('Username').fill('admin');
await page.getByLabel('Password').fill('Demo!Pass123');
await page.getByRole('button', { name: 'Sign In' }).click();
await page.waitForURL('http://localhost:5173/');
await page.goto('http://localhost:5173/outbound'); await page.waitForTimeout(500);
await page.getByRole('button', { name: 'Open' }).first().click(); await page.waitForTimeout(700);
await page.screenshot({ path: S + '/shots/order.png' });
await page.keyboard.press('Escape');
await page.goto('http://localhost:5173/inbound'); await page.waitForTimeout(500);
await page.getByRole('button', { name: 'New receipt' }).click(); await page.waitForTimeout(500);
await page.screenshot({ path: S + '/shots/newreceipt.png' });
await page.keyboard.press('Escape');
await page.goto('http://localhost:5173/picks'); await page.waitForTimeout(500);
await page.screenshot({ path: S + '/shots/picks.png' });
await browser.close();
